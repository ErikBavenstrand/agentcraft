-- The frame model (harness/frames.lua) and layout solver (harness/layout.lua)
-- that dev/render/render.lua draws from.
local H = require("harness")
local layout = require("layout")

local function Solve(env, obj)
  local s = layout.New(env.W, { w = 1280, h = 800 })
  return s:Rect(obj), s
end

test("anchors resolve to screen rectangles (y-up offsets, parent default)", function()
  local env = H.boot({})
  local G = env.G
  local f = G.CreateFrame("Frame", nil, G.UIParent)
  f:SetSize(200, 100)
  f:SetPoint("CENTER")
  local r = Solve(env, f)
  eq(r.l, 540); eq(r.t, 350); eq(r.r, 740); eq(r.b, 450)
  local c = G.CreateFrame("Button", nil, f)
  c:SetSize(20, 10)
  c:SetPoint("TOPLEFT", 5, -7)            -- relative to parent, y up
  r = Solve(env, c)
  eq(r.l, 545); eq(r.t, 357)
  local d = G.CreateFrame("Frame", nil, f)
  d:SetPoint("TOPLEFT", c, "BOTTOMRIGHT", 2, 0)
  d:SetPoint("BOTTOMRIGHT", -10, 10)      -- two anchors decide the size
  r = Solve(env, d)
  eq(r.l, 567); eq(r.t, 367); eq(r.r, 730); eq(r.b, 440)
  eq(d:GetWidth(), 163)
  local t = f:CreateTexture(nil, "BACKGROUND")
  t:SetAllPoints()
  r = Solve(env, t)
  eq(r.l, 540); eq(r.b, 450)
end)

test("scale multiplies size and offsets; scroll child sits at the scroll frame's top-left", function()
  local env = H.boot({})
  local G = env.G
  local f = G.CreateFrame("Frame", nil, G.UIParent)
  f:SetScale(2)
  f:SetSize(10, 10)
  f:SetPoint("TOPLEFT", 3, -4)
  local r = Solve(env, f)
  eq(r.l, 6); eq(r.t, 8); eq(r.r, 26); eq(r.b, 28)
  local sf = G.CreateFrame("ScrollFrame", nil, G.UIParent, "UIPanelScrollFrameTemplate")
  sf:SetPoint("TOPLEFT", 100, -100)
  sf:SetSize(50, 50)
  local child = G.CreateFrame("Frame", nil, nil)
  child:SetSize(50, 300)
  sf:SetScrollChild(child)
  r = Solve(env, child)
  eq(r.l, 100); eq(r.t, 100); eq(r.b, 400)
  ok(sf.ScrollBar, "template made a scroll bar")
end)

test("circular and missing anchors are reported, not raised", function()
  local env = H.boot({})
  local G = env.G
  local a = G.CreateFrame("Frame", "CycleA", G.UIParent)
  local b = G.CreateFrame("Frame", "CycleB", G.UIParent)
  a:SetPoint("LEFT", b, "RIGHT"); a:SetSize(5, 5)
  b:SetPoint("LEFT", a, "RIGHT"); b:SetSize(5, 5)
  local r, s = Solve(env, a)
  eq(r, nil)
  ok(tostring(s.problems[a]):find("circular"), "cycle named: " .. tostring(s.problems[a]))
  local lone = G.CreateFrame("Frame", nil, G.UIParent)
  r, s = Solve(env, lone)
  eq(r, nil)
  ok(tostring(s.problems[lone]):find("no anchors"), tostring(s.problems[lone]))
end)

test("templates: known ones add regions, unknown ones are recorded", function()
  local env = H.boot({})
  local G = env.G
  local b = G.CreateFrame("Button", nil, G.UIParent, "UIPanelButtonTemplate")
  eq(b:GetWidth(), 40)
  b:SetText("Apply")
  eq(b:GetFontString():GetText(), "Apply")
  local x = G.CreateFrame("Frame", nil, G.UIParent, "BackdropTemplate, NoSuchTemplate")
  eq(x._unknownTemplates[1], "NoSuchTemplate")
  ok(G.C_XMLUtil.GetTemplateInfo("PortraitFrameTemplate"), "emulated templates report as present")
  eq(G.C_XMLUtil.GetTemplateInfo("NoSuchTemplate"), nil)
end)

test("font strings measure their text and size from anchors", function()
  local env = H.boot({})
  local G = env.G
  local f = G.CreateFrame("Frame", nil, G.UIParent)
  f:SetSize(100, 20); f:SetPoint("CENTER")
  local fs = f:CreateFontString(nil, "OVERLAY", "GameFontNormal")
  fs:SetText("|cffff0000Red|r text")
  ok(fs:GetStringWidth() > 30 and fs:GetStringWidth() < 70, "width " .. fs:GetStringWidth())
  fs:SetPoint("LEFT")
  local r = Solve(env, fs)
  ok(math.abs((r.r - r.l) - fs:GetStringWidth()) < 0.01, "unbounded text keeps its own width")
  eq(r.b - r.t, 12)
  fs:SetWidth(30)
  r = Solve(env, fs)
  eq(r.b - r.t, 24, "wraps to two lines at 30px")
end)
